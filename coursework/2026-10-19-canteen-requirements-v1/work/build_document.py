def para(text, style=None, bold=None, size=None, keep=False, space_after=None):
    p = doc.add_paragraph(style=style)
    r = p.add_run(text)
    if bold is not None: r.bold = bold
    if size: r.font.size = Pt(size)
    if keep: p.paragraph_format.keep_with_next = True
    if space_after is not None: p.paragraph_format.space_after=Pt(space_after)
    return p

def pair(zh, ru, style=None, size=None, compact=False):
    p=para(zh,style=style,size=size,keep=True,space_after=2 if compact else 3)
    p2=para(ru,style=style,size=size,space_after=5 if compact else 7)
    for r in p2.runs:
        rp=r._element.get_or_add_rPr(); lang=OxmlElement('w:lang'); lang.set(qn('w:val'),'ru-RU'); rp.append(lang)
    return p,p2

def heading(zh, ru, level=1):
    p,p2=pair(zh,ru,style=f'Heading {level}',compact=True)
    p.paragraph_format.space_before=Pt(8)
    p2.paragraph_format.space_before=Pt(0)
    for r in p2.runs: r.font.size=Pt(13 if level==1 else 11.5)
    return p,p2

