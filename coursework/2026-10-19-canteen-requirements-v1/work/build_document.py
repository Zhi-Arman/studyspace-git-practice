def cell_text(cell, value, size=10.4, header=False, center=False):
    cell.text=''
    vals=value if isinstance(value,(tuple,list)) else [value]
    for i,t in enumerate(vals):
        p=cell.paragraphs[0] if i==0 else cell.add_paragraph()
        p.paragraph_format.space_after=Pt(2)
        p.paragraph_format.space_before=Pt(1)
        p.paragraph_format.line_spacing=1.04
        p.paragraph_format.keep_with_next=False
        p.alignment=WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
        r=p.add_run(str(t)); r.font.size=Pt(size); r.bold=header
        if header: r.font.color.rgb=RGBColor(255,255,255)
    cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER

def table(headers, rows, widths, size=10.4, centered=()):
    t=doc.add_table(rows=1, cols=len(headers))
    t.autofit=False; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,w in enumerate(widths):
        t.columns[i].width=Inches(w)
    borders=OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        e=OxmlElement('w:'+edge); e.set(qn('w:val'),'single'); e.set(qn('w:sz'),'5'); e.set(qn('w:color'),'D9D9D9'); borders.append(e)
    t._tbl.tblPr.append(borders)
    margins=OxmlElement('w:tblCellMar')
    for edge,val in [('top','75'),('bottom','75'),('left','100'),('right','100')]:
        el=OxmlElement('w:'+edge); el.set(qn('w:w'),val); el.set(qn('w:type'),'dxa'); margins.append(el)
    t._tbl.tblPr.append(margins)
    for i,h in enumerate(headers):
        c=t.rows[0].cells[i]; c.width=Inches(widths[i]); cell_text(c,h,size,True,i in centered)
        shd=OxmlElement('w:shd'); shd.set(qn('w:fill'),'253B53'); c._tc.get_or_add_tcPr().append(shd)
    trh=OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(trh)
    for ridx,row in enumerate(rows):
        rc=t.add_row()
        cant=OxmlElement('w:cantSplit'); rc._tr.get_or_add_trPr().append(cant)
        for i,val in enumerate(row):
            c=rc.cells[i]; c.width=Inches(widths[i]); cell_text(c,val,size,False,i in centered)
            if ridx%2==1:
                shd=OxmlElement('w:shd'); shd.set(qn('w:fill'),'F1F5F8'); c._tc.get_or_add_tcPr().append(shd)
    doc.add_paragraph().paragraph_format.space_after=Pt(2)
    return t

