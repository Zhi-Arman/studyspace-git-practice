def fonts(style, size, bold=False):
    style.font.name = 'Times New Roman'
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = RGBColor(0, 0, 0)
    rpr = style.element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.insert(0, rf)
    for attr, val in [('ascii', 'Times New Roman'), ('hAnsi', 'Times New Roman'), ('eastAsia', 'Songti SC'), ('cs', 'Times New Roman')]:
        rf.set(qn('w:' + attr), val)
    for theme in ['asciiTheme', 'hAnsiTheme', 'eastAsiaTheme', 'cstheme']:
        rf.attrib.pop(qn('w:' + theme), None)

